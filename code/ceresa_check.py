"""
Checks for the Laga-Shnidman criteria, for a curve C with a group action.

Input : a generating vector (c_1, ..., c_r) of a finite group G: permutations
        that generate G and satisfy c_1 * ... * c_r = 1.  They describe the
        curves C with a G-action and C/G = P^1, branched at r points with
        monodromy c_1, ..., c_r.
Output: check(vector) returns
          genus   the genus of C
          A       dim (wedge^3 H^1(C))^G.        A = 0: criterion (A) applies, the Ceresa
                                                 cycle is torsion in the Chow group
          B       dim (wedge^3 H^0(C,Omega^1))^G. B = 0: criterion (B) applies, torsion in the
                                                 Griffiths group, assuming the Hodge conjecture
          nonhyp  True if the test below proves that C is not hyperelliptic

Method.  Let V = H^0(C, Omega^1).  For x != 1 in G, the fixed points of x above the
i-th branch point are the cosets h<c_i> with h^-1 x h = c_i^k, and x rotates the
tangent space there by exp(2 pi i k / e_i).  The holomorphic Lefschetz formula gives
    chi_V(x) = 1 - sum over fixed points of 1 / (1 - conj(rotation)),
and chi_V(1) = g.  Then H^1(C) = V + conj(V), and for any character chi
    dim (wedge^3)^G = 1/|G| * sum_x (chi(x)^3 - 3 chi(x) chi(x^2) + 2 chi(x^3)) / 6.

Non-hyperellipticity.  If C is hyperelliptic, y^2 = f(x), every automorphism s acts on
the forms x^i dx / y (i = 0..g-1) with eigenvalues lambda * mu^i: a geometric progression.
So if some s in G has eigenvalues on V that do not form one, C is not hyperelliptic.

Needs only Python 3.   Run:  python3 ceresa_check.py
A permutation of {0, ..., n-1} is a tuple p, sending i to p[i].
"""
import cmath
from fractions import Fraction
from itertools import product


# ---------------------------------------------------------------- permutations
def mul(p, q):
    """The permutation 'first p, then q'."""
    return tuple(q[i] for i in p)


def inverse(p):
    inv = [0] * len(p)
    for i, j in enumerate(p):
        inv[j] = i
    return tuple(inv)


def power(p, k):
    result = tuple(range(len(p)))
    for _ in range(k):
        result = mul(result, p)
    return result


def order(p):
    identity, q, k = tuple(range(len(p))), p, 1
    while q != identity:
        q, k = mul(q, p), k + 1
    return k


def cycles(n, *cycs):
    """cycles(5, (0, 1, 2), (3, 4)) is the permutation (0 1 2)(3 4) of {0,...,4}."""
    p = list(range(n))
    for cyc in cycs:
        for i, a in enumerate(cyc):
            p[a] = cyc[(i + 1) % len(cyc)]
    return tuple(p)


def group(generators):
    """All elements of the group generated by the given permutations."""
    identity = tuple(range(len(generators[0])))
    elements, frontier = {identity}, [identity]
    while frontier:
        new = []
        for x in frontier:
            for s in generators:
                y = mul(x, s)
                if y not in elements:
                    elements.add(y)
                    new.append(y)
        frontier = new
    return elements


def conjugacy_classes(G):
    """Returns (class_of, representatives, sizes): class_of[x] is the index of the class of x."""
    class_of, reps, sizes = {}, [], []
    inverses = {h: inverse(h) for h in G}
    for x in sorted(G):
        if x in class_of:
            continue
        cls = {mul(mul(inverses[h], x), h) for h in G}
        for y in cls:
            class_of[y] = len(reps)
        reps.append(x)
        sizes.append(len(cls))
    return class_of, reps, sizes


# ---------------------------------------------------------------- the checks
def genus(G, vector):
    """Riemann-Hurwitz: 2g - 2 = |G| (r - 2 - sum 1/order(c_i))."""
    return 1 + len(G) * (len(vector) - 2 - sum(Fraction(1, order(c)) for c in vector)) / 2


def characters(G, vector, classes=None):
    """Class functions (lists indexed by conjugacy class): chi_V (complex) and #Fix (exact)."""
    class_of, reps, sizes = classes or conjugacy_classes(G)
    inverses = {h: inverse(h) for h in G}
    g = genus(G, vector)
    powers = []                                   # for each c_i: {c_i^k: k}
    for c in vector:
        table, q = {}, tuple(range(len(c)))
        for k in range(order(c)):
            table[q] = k
            q = mul(q, c)
        powers.append(table)
    chiV, fix = [], []
    for x in reps:
        if order(x) == 1:
            chiV.append(complex(g)); fix.append(None)
            continue
        value, count = 1 + 0j, Fraction(0)
        conjugates = [mul(mul(inverses[h], x), h) for h in G]
        for table in powers:
            e = len(table)
            for y in conjugates:
                k = table.get(y)
                if k:                                              # y = c_i^k with k != 0
                    count += Fraction(1, e)
                    value -= (1 / (1 - cmath.exp(-2j * cmath.pi * k / e))) / e
        chiV.append(value); fix.append(count)
    return chiV, fix


def wedge3_invariants(chi, G, class_of, reps, sizes):
    total = 0
    for i, x in enumerate(reps):
        x2, x3 = class_of[mul(x, x)], class_of[power(x, 3)]
        total += sizes[i] * (chi[i]**3 - 3 * chi[i] * chi[x2] + 2 * chi[x3]) / 6
    return total / len(G)


def is_geometric_progression(mult, n, g):
    """mult[j] = multiplicity of exp(2 pi i j / n).  Is the multiset {a + i*m mod n : i < g}?"""
    for a in range(n):
        if not mult[a]:
            continue
        for m in range(n):
            seen = [0] * n
            for i in range(g):
                seen[(a + i * m) % n] += 1
            if seen == mult:
                return True
    return False


def proves_nonhyperelliptic(G, chiV, class_of, reps, g):
    for x in reps:
        n = order(x)
        if n == 1:
            continue
        values = [chiV[class_of[power(x, k)]] for k in range(n)]
        mult = [round((sum(values[k] * cmath.exp(-2j * cmath.pi * j * k / n) for k in range(n)) / n).real)
                for j in range(n)]
        if not is_geometric_progression(mult, n, g):
            return True
    return False


def check(vector):
    G = group(list(vector))
    identity = tuple(range(len(vector[0])))
    product_ = identity
    for c in vector:
        product_ = mul(product_, c)
    assert product_ == identity, "the generating vector must have product 1"
    g = genus(G, vector)
    assert g.denominator == 1 and g >= 0, "these orders do not give a curve"
    g = int(g)
    classes = conjugacy_classes(G)
    class_of, reps, sizes = classes
    chiV, fix = characters(G, vector, classes)
    chiW = [Fraction(2 * g) if f is None else 2 - f for f in fix]
    A = wedge3_invariants(chiW, G, *classes)
    B = wedge3_invariants(chiV, G, *classes)
    assert A.denominator == 1 and abs(B - round(B.real)) < 1e-6
    return {"order": len(G), "signature": tuple(order(c) for c in vector), "genus": g,
            "A": int(A), "B": round(B.real),
            "nonhyp": g >= 3 and proves_nonhyperelliptic(G, chiV, class_of, reps, g)}


def generating_vectors(generators, orders):
    """Generating vectors with the given orders, one for each choice of conjugacy classes."""
    G = group(generators)
    class_of, reps, sizes = conjugacy_classes(G)
    by_order = {}
    for x in G:
        by_order.setdefault(order(x), []).append(x)
    seen = set()
    firsts = [x for x in reps if order(x) == orders[0]]
    for a in firsts:
        for middle in product(*[by_order.get(n, []) for n in orders[1:-1]]):
            p = a
            for b in middle:
                p = mul(p, b)
            last = inverse(p)
            if order(last) != orders[-1]:
                continue
            vector = (a,) + middle + (last,)
            key = tuple(sorted(class_of[c] for c in vector))
            if key in seen or len(group(list(vector))) != len(G):
                continue
            seen.add(key)
            yield vector


def report(name, generators, orders):
    """Print one line for each different outcome among the refined passports."""
    seen = set()
    for vector in generating_vectors(generators, orders):
        r = check(vector)
        line = (f"{name}, signature {orders}: genus {r['genus']}, A = {r['A']}, B = {r['B']}, "
                f"non-hyperelliptic {'proved' if r['nonhyp'] else 'not decided'}")
        if line not in seen:
            seen.add(line)
            print(line)


